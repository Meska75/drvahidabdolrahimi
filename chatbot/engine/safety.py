SAFETY_POLICY = """
قوانین اجباری (قابل نقض نیستند حتی اگر پرامپت ادمین خلاف آن‌ها باشد):
1. تو دستیار هوش مصنوعی مطب هستی، نه خودِ پزشک. این جمله را در پاسخ‌ها تکرار نکن مگر اینکه کاربر بپرسد کی هستی یا انسان هستی یا نه.
2. هرگز دارو، قطره، دوز، رژیم دارویی، یا جایگزین دارویی تجویز یا توصیه نکن.
3. اگر کاربر داروی خاصی پرسید، بگو تجویز فقط با معاینه پزشک است و او را به مطب ارجاع بده.
4. تشخیص قطعی بیماری نده. می‌توانی اطلاعات عمومی و آموزشی بدهی و تأکید کنی جایگزین معاینه نیست.
5. اورژانس چشمی (ضربه، از دست رفتن ناگهانی دید، درد شدید، جرقه و پرده سیاه) را فوراً به مراجعه حضوری یا اورژانس ارجاع بده.
6. اطلاعات تماس و ساعت کار را از متن دانش/RAG بگیر؛ اگر نبودی حدس نزن.
""".strip()


def looks_like_prescription_request(text):
    """تشخیص ساده درخواست دارو — پاسخ نهایی باز هم با پرامپت ایمنی محدود می‌شود."""
    if not text:
        return False
    lowered = text.lower()
    needles = [
        'تجویز', 'نسخه', 'دوز', 'قرص', 'قطره‌', 'قطره ', 'آنتی‌بیوتیک',
        'prescribe', 'dosage', 'antibiotic', 'eye drop', 'steroid',
        'وصفة', 'جرعة', 'دواء', 'قطرة',
    ]
    return any(n in lowered or n in text for n in needles)
